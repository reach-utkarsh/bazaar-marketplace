import { randomBytes } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { env } from '../../config/env.js';
import { logger } from '../../lib/logger.js';

export interface StoredFile {
  key: string;
  url: string;
}

/**
 * Storage abstraction. `LocalDiskStorage` is used in development; a Cloudinary/S3
 * adapter only needs to implement these two methods.
 */
export interface StorageService {
  save(file: { buffer: Buffer; originalName: string; mimeType: string }): Promise<StoredFile>;
  remove(key: string): Promise<void>;
}

const EXT: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/gif': '.gif',
};

export class LocalDiskStorage implements StorageService {
  constructor(
    private readonly dir: string,
    private readonly publicPrefix = '/uploads',
  ) {}

  async save(file: { buffer: Buffer; originalName: string; mimeType: string }): Promise<StoredFile> {
    await mkdir(this.dir, { recursive: true });
    const ext = EXT[file.mimeType] ?? path.extname(file.originalName).toLowerCase();
    const key = `${Date.now()}-${randomBytes(8).toString('hex')}${ext}`;
    await writeFile(path.join(this.dir, key), file.buffer);
    return { key, url: `${this.publicPrefix}/${key}` };
  }

  async remove(key: string): Promise<void> {
    // Keys are generated by us; still guard against path traversal.
    const safe = path.basename(key);
    try {
      await unlink(path.join(this.dir, safe));
    } catch (err) {
      logger.warn(`Could not delete upload ${safe}`, (err as Error).message);
    }
  }
}

export const uploadDir = path.resolve(process.cwd(), env.UPLOAD_DIR);
export const storage: StorageService = new LocalDiskStorage(uploadDir);
